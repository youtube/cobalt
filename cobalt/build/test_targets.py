"""Platform build skipping and test target pruning via native gn analyze."""

import argparse
import json
from pathlib import Path
import subprocess
import sys
import tempfile
from typing import Any, Callable, Dict, List, Optional, Set, Tuple, Union

# Infrastructure prefixes that trigger unconditional fail-open full builds.
_ALWAYS_RUN_PREFIXES = (
    '.github/',
    '.gn',
    '.vpython3',
    'DEPS',
    'build/',
    'cobalt/build/',
    'cobalt/docker/',
    'cobalt/testing/filters',
    'cobalt/tools/',
    'docker-compose.yaml',
    'starboard/build/',
    'starboard/tools/',
    'testing/',
    'tools/',
)

RunGnCallable = Callable[[List[str]], Any]


def is_infra_file(path: str) -> bool:
  """Returns True if the file should trigger an unconditional full run."""
  clean = path.strip().lstrip('/').removeprefix('./')
  return (clean.startswith(_ALWAYS_RUN_PREFIXES) or clean.endswith(
      ('.gn', '.gni')))


def _canonical_label(label: str) -> str:
  """Canonicalizes a GN label to //path/to/target:target."""
  if not label or label == 'null':
    return ''
  base = label.split('(')[0]
  if not base.startswith('//'):
    base = '//' + base.lstrip('/')
  if ':' not in base:
    base = base + ':' + base.rstrip('/').rsplit('/', 1)[-1]
  return base


def _resolve_labels(all_labels: Set[str], targets: List[str]) -> List[str]:
  """Expands target labels against valid build labels from gn ls."""
  resolved = set()
  for t in targets:
    if not t or t == 'null':
      continue
    if not all_labels:
      resolved.add(_canonical_label(t))
    elif t in all_labels:
      resolved.add(t)
    else:
      c = _canonical_label(t)
      matches = [
          lbl for lbl in all_labels if _canonical_label(lbl) == c or
          (':' not in t and _canonical_label(lbl).endswith(f':{t}'))
      ]
      resolved.update(matches or [c])
  return sorted(resolved)


def should_skip_from_deps(deps_file: Union[str, Path],
                          files: List[str]) -> bool:
  """Checks if changed files intersect precomputed target dependencies."""
  if not files or any(is_infra_file(f) for f in files):
    return False
  raw = json.loads(Path(deps_file).read_text(encoding='utf-8'))
  flist = ([f for fl in raw.values() if isinstance(fl, list)
            for f in fl] if isinstance(raw, dict) else raw)
  deps = ({f.lstrip('/').removeprefix('./') for f in flist} if isinstance(
      flist, list) else set())
  if not deps:
    raise ValueError(f'Empty dependencies parsed from {deps_file}')
  return not any(
      f.strip().lstrip('/').removeprefix('./') in deps for f in files)


def load_manifest(
    manifest_path: Optional[Union[str, Path]],
) -> Tuple[Dict[str, Any], List[Dict[str, Any]]]:
  """Loads test manifest, separating metadata header from test entries."""
  if not manifest_path or not Path(manifest_path).exists():
    return {'disabled': False}, []
  try:
    data = json.loads(Path(manifest_path).read_text(encoding='utf-8'))
    if isinstance(data, list) and data and isinstance(data[0], dict):
      header = data[0]
    else:
      header = {'disabled': False}
    tests = ([x for x in data[1:] if isinstance(x, dict) and 'target' in x]
             if isinstance(data, list) else [])
    return header, tests
  except Exception as e:  # pylint: disable=broad-except
    sys.stderr.write(f'Warning: Error loading manifest {manifest_path}: {e}\n')
    return {'disabled': False}, []


def format_filter_file(test_targets: List[str]) -> str:
  """Formats test targets into Chromium .filter file format."""
  cleaned = sorted(t.strip().lstrip('/') for t in test_targets if t.strip())
  return '\n'.join(['# Generated by cobalt/build/test_targets.py', *cleaned
                   ]) + '\n'


# pylint: disable=too-many-positional-arguments
def run_analysis(
    out_dir: Optional[Union[str, Path]],
    changed_files: List[str],
    targets: List[str],
    test_manifest_path: Optional[Union[str, Path]],
    run_gn: Optional[RunGnCallable] = None,
    deps_file: Optional[Union[str, Path]] = None,
) -> Tuple[bool, List[Dict[str, Any]]]:
  """Performs platform skip and test target pruning analysis."""
  header, all_tests = load_manifest(test_manifest_path)
  full_manifest = [header] + all_tests

  if not changed_files or any(is_infra_file(f) for f in changed_files):
    return False, full_manifest

  if deps_file:
    try:
      skip = should_skip_from_deps(deps_file, changed_files)
      return (True, [header]) if skip else (False, full_manifest)
    except Exception as e:  # pylint: disable=broad-except
      sys.stderr.write(f'Warning: Error analyzing precomputed deps: {e}\n')
      return False, full_manifest

  if not out_dir:
    sys.stderr.write('Warning: Neither out_dir nor deps_file specified.\n')
    return False, full_manifest

  if run_gn is None:

    def _default_run_gn(args: List[str]) -> subprocess.CompletedProcess:
      return subprocess.run(['gn', *args],
                            check=True,
                            capture_output=True,
                            text=True,
                            timeout=600)

    run_gn = _default_run_gn

  try:
    ls_res = run_gn(['ls', str(out_dir)])
    all_labels = set(
        ls_res.stdout.split() if hasattr(ls_res, 'stdout') else ls_res)
    clean_files = [
        '//' + f.strip().removeprefix('./').lstrip('/') for f in changed_files
    ]
    req = {
        'files':
            clean_files,
        'additional_compile_targets':
            _resolve_labels(all_labels, targets),
        'test_targets':
            _resolve_labels(all_labels,
                            [t['target'] for t in all_tests if 'target' in t]),
    }

    with tempfile.TemporaryDirectory() as tmp:
      in_file, out_file = Path(tmp) / 'in.json', Path(tmp) / 'out.json'
      in_file.write_text(json.dumps(req), encoding='utf-8')
      res = run_gn(['analyze', str(out_dir), str(in_file), str(out_file)])
      if isinstance(res, dict):
        result = res
      elif out_file.exists() and out_file.stat().st_size > 0:
        result = json.loads(out_file.read_text(encoding='utf-8'))
      elif hasattr(res, 'stdout') and res.stdout.strip():
        result = json.loads(res.stdout)
      else:
        result = {}

    if 'error' in result:
      raise RuntimeError(result['error'])

    status = result.get('status')
    if status == 'No dependency':
      return True, [header]
    if status == 'Found dependency':
      c_targets = result.get('compile_targets', [])
      t_targets = {_canonical_label(t) for t in result.get('test_targets', [])}
      if not c_targets and not t_targets:
        return True, [header]
      pruned = [
          t for t in all_tests
          if _canonical_label(t.get('target', '')) in t_targets
      ]
      return False, [header] + pruned
    if status == 'Found dependency (all)':
      return False, full_manifest

    sys.stderr.write(f'Warning: Unknown gn status {status!r}, failing open.\n')
    return False, full_manifest
  except Exception as e:  # pylint: disable=broad-except
    sys.stderr.write(f'Warning: gn analyze failed: {e}. Failing open.\n')
    return False, full_manifest


def main(argv: Optional[List[str]] = None) -> int:
  """Command line entry point."""
  parser = argparse.ArgumentParser(
      description='Platform build skipping and test pruning via gn analyze.')
  parser.add_argument('--out-dir', help='Path to GN output directory.')
  parser.add_argument('--deps-file', help='Path to precomputed target deps.')
  parser.add_argument('--changed-files', help='Path to changed files list.')
  parser.add_argument(
      '--targets', default='[]', help='JSON array or name of compile targets.')
  parser.add_argument(
      '--test-targets-json', help='Path to static test_targets.json.')
  parser.add_argument(
      '--output', help='Path to write pruned test_targets.json.')
  parser.add_argument(
      '--filter-output', help='Path to write .filter file (or - for stdout).')
  parser.add_argument('--github-output', help='Path to $GITHUB_OUTPUT file.')
  args = parser.parse_args(argv)

  files = []
  if args.changed_files and Path(args.changed_files).exists():
    files = [
        l.strip() for l in Path(args.changed_files).read_text(
            encoding='utf-8', errors='replace').splitlines() if l.strip()
    ]

  try:
    targets = json.loads(args.targets) if args.targets else []
  except Exception:  # pylint: disable=broad-except
    targets = [args.targets] if args.targets else []

  skip, pruned_manifest = run_analysis(
      out_dir=args.out_dir,
      changed_files=files,
      targets=targets if isinstance(targets, list) else [targets],
      test_manifest_path=args.test_targets_json,
      deps_file=args.deps_file,
  )

  test_targets_list = [
      t['target']
      for t in pruned_manifest
      if isinstance(t, dict) and 'target' in t
  ]
  count = len(test_targets_list)

  if skip:
    summary = ('[test_targets] Platform skip: true (0 compile targets, 0 tests'
               ' affected)')
  elif test_targets_list:
    joined_targets = ', '.join(test_targets_list)
    summary = (f'[test_targets] Platform skip: false ({count} tests affected: '
               f'{joined_targets})')
  else:
    summary = '[test_targets] Platform skip: false (0 tests affected)'

  manifest_json = json.dumps(pruned_manifest, indent=2) + '\n'
  if args.output:
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(manifest_json, encoding='utf-8')
    print(summary)
  else:
    print(manifest_json, end='')
    sys.stderr.write(summary + '\n')

  if args.filter_output:
    flt = format_filter_file(test_targets_list)
    if args.filter_output == '-':
      print(flt, end='')
    else:
      flt_path = Path(args.filter_output)
      flt_path.parent.mkdir(parents=True, exist_ok=True)
      flt_path.write_text(flt, encoding='utf-8')

  if args.github_output:
    gh = Path(args.github_output)
    gh.parent.mkdir(parents=True, exist_ok=True)
    skip_str = 'true' if skip else 'false'
    with open(gh, 'a', encoding='utf-8') as f:
      f.write(f'skip={skip_str}\n'
              f'test_targets_json={json.dumps(test_targets_list)}\n'
              f'test_targets_count={count}\n')

  return 0


if __name__ == '__main__':
  sys.exit(main())
